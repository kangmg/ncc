from __future__ import annotations

import json
import re
from dataclasses import dataclass
from pathlib import Path

from jsonschema import Draft202012Validator

from . import config, model, refs

IMAGE_RE = re.compile(r"!\[[^\]]*\]\(([^)\s]+)")
CITE_RE = re.compile(r"(?<![\w@])@([A-Za-z0-9_][A-Za-z0-9_:.-]*[A-Za-z0-9_])")


@dataclass
class Finding:
    level: str
    where: str
    message: str

    def __str__(self) -> str:
        return f"[{self.level}] {self.where}: {self.message}"


def _validator(name: str) -> Draft202012Validator:
    schema = json.loads((config.SCHEMA / name).read_text(encoding="utf-8"))
    return Draft202012Validator(schema, format_checker=Draft202012Validator.FORMAT_CHECKER)


def _schema_findings(validator: Draft202012Validator, data: dict, where: str) -> list[Finding]:
    out = []
    for err in sorted(validator.iter_errors(data), key=lambda e: list(e.path)):
        location = "/".join(str(p) for p in err.path) or "(root)"
        message = err.message
        if err.validator == "oneOf" and location == "(root)":
            message = "provide exactly one manuscript body: `sections`, `body_file`, or `pdf`"
        out.append(Finding("error", where, f"{location}: {message}"))
    return out


def _safe_relative(base: Path, rel: str) -> Path | None:
    if rel.startswith(("/", "\\")) or re.match(r"^[a-zA-Z]+:", rel):
        return None
    target = (base / rel).resolve()
    return target if target.is_relative_to(base.resolve()) else None


def markdown_bodies(paper: dict, base: Path) -> list[str]:
    if "sections" in paper:
        return [s["body"] for s in paper["sections"]]
    body_file = paper.get("body_file", "")
    if body_file.endswith(".md") and (base / body_file).exists():
        return [(base / body_file).read_text(encoding="utf-8")]
    return []


def validate_paper(paper: dict, base: Path, where: str, resolve_dois: bool = False) -> list[Finding]:
    findings = _schema_findings(_validator("paper.schema.json"), paper, where)
    if findings:
        return findings

    def check_file(rel: str, label: str) -> None:
        target = _safe_relative(base, rel)
        if target is None:
            findings.append(Finding("error", where, f"{label} `{rel}` must be a relative path inside the manuscript folder"))
        elif not target.exists():
            findings.append(Finding("error", where, f"{label} `{rel}` not found"))

    for key in ("toc_graphic", "body_file", "pdf", "bibliography"):
        if key in paper:
            check_file(paper[key], key)
    for item in paper.get("supporting_information", []):
        check_file(item["file"], "supporting file")

    bodies = markdown_bodies(paper, base)
    for body in bodies:
        for src in IMAGE_RE.findall(body):
            if not src.startswith(("http://", "https://")):
                check_file(src, "figure")

    if not any(a.get("github") for a in paper["authors"]):
        findings.append(Finding("error", where, "at least one author needs a `github` handle (used for authorship checks)"))

    ids = [r["id"] for r in paper.get("references", [])]
    duplicates = {i for i in ids if ids.count(i) > 1}
    if duplicates:
        findings.append(Finding("error", where, f"duplicate reference ids: {', '.join(sorted(duplicates))}"))
    if bodies and "bibliography" not in paper:
        known = set(ids)
        cited = {c for body in bodies for c in CITE_RE.findall(body) if not c.startswith(("fig:", "tbl:", "eq:"))}
        missing = sorted(cited - known)
        if missing:
            findings.append(Finding("error", where, f"cited but not in `references`: {', '.join(missing)}"))

    findings += _ai_findings(paper.get("ai_contributions"), where)
    if paper.get("tags") and not model.subjects_for(paper["tags"]):
        names = ", ".join(sorted({t for s in config.journal()["subjects"] for t in s["tags"]}))
        findings.append(Finding("warning", where, f"no tag matches a journal subject; consider adding one of: {names}"))
    if resolve_dois:
        for ref in paper.get("references", []):
            if ref.get("doi") and refs.resolve_doi(ref["doi"]) is None:
                findings.append(Finding("error", where, f"reference `{ref['id']}`: DOI {ref['doi']} does not resolve"))

    target = config.journal()["translation"]["target"]
    if paper.get("language", "en") != target and model.load_translation(base) is None:
        findings.append(Finding("warning", where, f"no `translation.{target}.yml` yet; it is generated by AI at acceptance"))
    return findings


def _ai_findings(ai: dict | None, where: str) -> list[Finding]:
    if not ai:
        return []
    findings = []
    agents = ai.get("agents", [])
    if ai["level"] == "none" and agents:
        findings.append(Finding("error", where, "ai_contributions: level `none` cannot list agents"))
    if ai["level"] in ("substantial", "agent-led"):
        if not agents:
            findings.append(Finding("error", where, f"ai_contributions: level `{ai['level']}` needs at least one entry in `agents`"))
        if len((ai.get("oversight") or "").strip()) < 10:
            findings.append(Finding("error", where, f"ai_contributions: level `{ai['level']}` needs an `oversight` statement"))
    if ai["level"] == "agent-led" and not ai.get("logs"):
        findings.append(Finding("warning", where, "ai_contributions: agent-led work should link run logs or transcripts in `logs`"))
    return findings


def validate_article(article_dir: Path, resolve_dois: bool = False) -> list[Finding]:
    where = str(article_dir.relative_to(config.ROOT))
    record_path = article_dir / "record.yml"
    if not record_path.exists():
        return [Finding("error", where, "record.yml missing")]
    record = config.load_yaml(record_path)
    findings = _schema_findings(_validator("record.schema.json"), record, f"{where}/record.yml")
    if findings:
        return findings
    if record["id"] != article_dir.name:
        findings.append(Finding("error", where, f"record id {record['id']} does not match folder name"))
    numbers = [v["version"] for v in record["versions"]]
    if numbers != list(range(1, len(numbers) + 1)):
        findings.append(Finding("error", where, f"versions must be 1..n in order, got {numbers}"))
    if record["status"] == "withdrawn" and "withdrawn" not in record:
        findings.append(Finding("error", where, "withdrawn articles need a `withdrawn: {date, reason}` block"))
    for entry in record["versions"]:
        vdir = article_dir / f"v{entry['version']}"
        paper_path = vdir / "paper.yml"
        if not paper_path.exists():
            findings.append(Finding("error", where, f"v{entry['version']}/paper.yml missing"))
            continue
        paper = config.load_yaml(paper_path)
        findings += validate_paper(paper, vdir, str(paper_path.relative_to(config.ROOT)), resolve_dois)
        if entry["version"] > 1 and not (entry.get("changelog") or paper.get("changelog")):
            findings.append(Finding("error", where, f"v{entry['version']} needs a changelog"))
    return findings


def validate_paths(paths: list[Path], resolve_dois: bool = False) -> list[Finding]:
    findings: list[Finding] = []
    for path in paths:
        path = path.resolve()
        if path.is_file():
            path = path.parent
        if (path / "record.yml").exists():
            findings += validate_article(path, resolve_dois)
        elif (path / "paper.yml").exists():
            paper = config.load_yaml(path / "paper.yml")
            findings += validate_paper(paper, path, str(path / "paper.yml"), resolve_dois)
        else:
            findings.append(Finding("error", str(path), "no record.yml or paper.yml here"))
    return findings


def default_targets() -> list[Path]:
    targets = [a.dir for a in model.discover_articles()]
    targets += [e.dir for e in model.discover_examples()]
    return targets
